export async function GET(
    request: Request,
    { params }: { params: { sign: string } }
) {
    try {
        const sign = params.sign.toLowerCase();

        if (!HOROSCOPES[sign]) {
            return NextResponse.json(
                { error: 'Invalid zodiac sign' },
                { status: 400 }
            );
        }

        // Get random horoscope for the sign
        const horoscopes = HOROSCOPES[sign];
        const randomHoroscope = horoscopes[Math.floor(Math.random() * horoscopes.length)];

        return NextResponse.json({
            sign,
            text: randomHoroscope,
            date: new Date().toISOString().split('T')[0],
        });
    } catch (error) {
        console.error('Error fetching horoscope:', error);
        return NextResponse.json(
            { error: 'Failed to fetch horoscope' },
            { status: 500 }
        );
    }
}
