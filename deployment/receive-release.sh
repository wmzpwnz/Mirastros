#!/usr/bin/env bash
# Root-owned receiver used only by a restricted GitHub Actions SSH key.
set -euo pipefail
umask 027
release="${SSH_ORIGINAL_COMMAND:-}"
[[ "$release" =~ ^[0-9a-f]{40}$ ]] || { echo 'Expected a full Git commit SHA' >&2; exit 2; }
root=/srv/mirastros
test -f "$root/shared/backend.env"
archive="$(mktemp /srv/mirastros-release.XXXXXX.tar.gz)"
trap 'rm -f "$archive"' EXIT
# Limit the upload to 400 MB. The build artifact is much smaller.
head -c 400000001 > "$archive"
test "$(stat -c %s "$archive")" -le 400000000
python3 - "$archive" <<'PY'
import sys, tarfile, pathlib
with tarfile.open(sys.argv[1]) as archive:
    total = 0
    for member in archive:
        name = pathlib.PurePosixPath(member.name)
        if name.is_absolute() or '..' in name.parts or member.isdev() or member.isfifo():
            raise SystemExit('Unsafe archive member')
        if member.issym() or member.islnk():
            target = pathlib.PurePosixPath(member.linkname)
            if target.is_absolute():
                raise SystemExit('Absolute archive link')
        total += member.size
        if total > 1500000000:
            raise SystemExit('Release is too large')
PY
next="$(mktemp -d "$root/releases/$release.XXXXXX")"
chown mirastros:mirastros "$next"
chmod 750 "$next"
chown mirastros:mirastros "$archive"
runuser -u mirastros -- tar -xzf "$archive" --no-same-owner -C "$next"
runuser -u mirastros -- python3 -m venv "$next/venv"
runuser -u mirastros -- "$next/venv/bin/pip" install --no-cache-dir --disable-pip-version-check -r "$next/backend/requirements-server.txt"
(
  set -a
  # File is generated by the administrator with shell-compatible assignments.
  source "$root/shared/backend.env"
  set +a
  cd "$next/backend"
  runuser -u mirastros -- "$next/venv/bin/python" initialize_database.py --if-empty
)
previous="$(readlink -f "$root/current" || true)"
ln -s "$next" "$root/current.next"
mv -Tf "$root/current.next" "$root/current"
systemctl restart mirastros-api mirastros-web
ready=false
for attempt in $(seq 1 30); do
  if curl -fsS --max-time 5 http://127.0.0.1:8000/health/readiness >/dev/null && \
     curl -fsS --max-time 5 http://127.0.0.1:3000/auth/login >/dev/null; then
    ready=true; break
  fi
  sleep 2
done
if [ "$ready" != true ]; then
  if [ -n "$previous" ] && [ -d "$previous" ]; then
    ln -s "$previous" "$root/current.rollback"
    mv -Tf "$root/current.rollback" "$root/current"
    systemctl restart mirastros-api mirastros-web
  else
    systemctl stop mirastros-api mirastros-web
  fi
  echo 'Release failed health checks' >&2
  exit 1
fi
echo "Release $release is healthy"
